async function login() {
  const username = document.getElementById("username").value;
  const password = document.getElementById("password").value;
  const res = await fetch("/login", {
    method: "POST",
    headers: {
      "Content-Type": "application/json"
    },
    body: JSON.stringify({
      username,
      password
    })
  });

  const data = await res.json();
  const lang = localStorage.getItem("lang") || "en";
  const t = translations[lang] || translations.en;

  if (data.token) {
    localStorage.setItem("token", data.token);
    localStorage.setItem("username", data.username);
    localStorage.setItem("inviteCode", data.inviteCode);
    showMessage(t.success);
    setTimeout(() => {
      window.location.href = "/home.html";
    }, 3000);
  } else {
    if (data.msg === "Wrong password") {
      showMessage(t.wrongPassword);
    } else if (data.msg === "User not found") {
      showMessage(t.userNotFound);
    } else {
      showMessage(t.failed);

    }

  }
}

function changeLang(lang) {
  localStorage.setItem("lang", lang);
  const t = translations[lang] || translations.en;
  document.querySelector("h1").innerText = t.title;
  document.querySelector("h2").innerText = t.login;
  document.getElementById("username").placeholder = t.username;
  document.getElementById("password").placeholder = t.password;
  document.getElementById("rememberText").innerText = t.remember;
  document.querySelector(".login-btn").innerText = t.login;
  document.querySelector(".register").innerText = t.register;
  const flagFile = flags[lang] || flags.en;
  const languageName = names[lang] || names.en;
  document.getElementById("currentLanguage").innerHTML = `
    <img src="flags/${flagFile}" class="current-flag">
    <span>${languageName}</span>
  `;

  if (
    lang === "ar" ||
    lang === "ur" ||
    lang === "fa"
  ) {
    document.body.dir = "rtl";
  } else {
    document.body.dir = "ltr";
  }

  document.getElementById(
    "languagePopupOverlay"
  ).style.display = "none";
}

function toggleLanguage(){
  const popup =
    document.getElementById("languagePopupOverlay");
  popup.style.display = "flex";
}

function showMessage(text) {
  const msg = document.getElementById("customMessage");
  msg.innerText = text;
  msg.style.display = "block";
  setTimeout(() => {
    msg.style.display = "none";
  }, 3000);

}

function goRegister() {
  window.location.href = "/register.html";
}

window.onload = function(){
  const lang = localStorage.getItem("lang") || "en";
  changeLang(lang);
}